test('publish: 发布后工作副本清空（dirty 不再永真）', async () => {
  const svc = makeService()
  const seed = (await svc.getSpec('hr-assistant')).spec
  await svc.putSpec('hr-assistant', { ...seed, persona: '改过的 persona' }, 'u-dev')
  assert.equal((await svc.getSpec('hr-assistant')).dirty, true)
  await svc.publishSpec('hr-assistant', 0, 'u-admin') // → v1，把改过的 persona 发布
  const view = await svc.getSpec('hr-assistant')
  assert.equal(view.dirty, false, '发布后工作副本与最新修订一致，dirty 应为 false')
  assert.equal(view.version, 1)
  assert.equal(view.spec.persona, '改过的 persona', '发布后 editor 读取最新修订，含刚发布内容')
})

test('rollback: 回滚到指定修订 = 新版本，spec 回到该修订', async () => {
  const svc = makeService()
  await svc.publishSpec('hr-assistant', 0, 'u-admin') // v1（种子 persona）
  const seed = (await svc.getSpec('hr-assistant')).spec
  await svc.putSpec('hr-assistant', { ...seed, persona: '改过的 persona' }, 'u-dev')
  await svc.publishSpec('hr-assistant', 1, 'u-admin') // v2（改过）
  const r = await svc.rollback('hr-assistant', 1, 'u-admin')
  assert.equal(r.version, 3, '回滚产生新版本而非改写历史')
  const view = await svc.getSpec('hr-assistant')
  assert.equal(view.spec.persona, seed.persona, '回滚后 spec 回到 v1')
  const revs = await svc.listRevisions('hr-assistant')
  assert.deepEqual(revs.map((x) => x.version), [3, 2, 1])
})

