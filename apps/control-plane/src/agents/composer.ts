// AgentComposer（docs/agent-orchestration-design.md §5）
// 深度模块：把 cordis 语法（插件行 / 白名单 / host-plane 边界）藏在小接口后面。
// 调用者只需学 AgentSpec 和 validate / compile / serialize。

import { stringify } from 'yaml'
import { findMcpServer, findModel } from './catalog.js'
import type { AgentSpec, CapabilityCatalog, PluginGraph, PluginRow, ValidationResult } from './types.js'

const ID_RE = /^[a-z0-9][a-z0-9-]*$/

// 平台自建插件（spike 结论）：在 preset scope 内用 ctx.tools.restrict() 按
// serverName 白名单过滤 host 层 mcp-client 注册的 mcp__<server>__<raw> 工具。
// 包名占位，实现落地到 dsh-source/packages/platform/（见 §5 实现 4 修订）。
const MCP_VISIBILITY_PLUGIN = '@company/dsh-tool-mcp-visibility'

/** agent.cordis.yml 产物文件头，标明 generated，禁止手改。 */
const GENERATED_HEADER = '# GENERATED by AgentComposer — do not edit by hand.\n'

export class AgentComposer {
  constructor(readonly catalog: CapabilityCatalog) {}

  validate(spec: AgentSpec): ValidationResult {
    const errors: Array<{ path: string; message: string }> = []

    if (!ID_RE.test(spec.id)) {
      errors.push({ path: 'id', message: `id 须为 [a-z0-9][a-z0-9-]*（不以中划线开头），得到 "${spec.id}"` })
    }
    if (!spec.name.trim()) {
      errors.push({ path: 'name', message: 'name 不能为空' })
    }
    if (!spec.persona.trim()) {
      errors.push({ path: 'persona', message: 'persona 不能为空' })
    }

    const model = findModel(this.catalog, spec.modelRoute.provider, spec.modelRoute.model)
    if (!model) {
      errors.push({
        path: 'modelRoute',
        message: `modelRoute "${spec.modelRoute.provider}/${spec.modelRoute.model}" 不在能力目录中`,
      })
    }

    for (const serverName of spec.mcp) {
      if (!findMcpServer(this.catalog, serverName)) {
        errors.push({ path: `mcp`, message: `MCP server "${serverName}" 不在能力目录中` })
      }
    }

    return errors.length === 0 ? { ok: true } : { ok: false, errors }
  }

  /** spec → PluginGraph（IR，不是 YAML）。行顺序稳定，保证同一 spec 逐字节同一产物。 */
  compile(spec: AgentSpec): PluginGraph {
    const rows: PluginRow[] = []

    // 1. persona：dsh-persona 在 preset scope 内 shadow 全局 deployment:persona（决策 7）。
    rows.push({
      id: 'persona',
      name: '@deepseek-ai/dsh-persona',
      config: { text: spec.persona },
    })

    // 2. 模型路由：pinned 不写进 YAML（决策 1：强制点在控制面 + 网关）。
    rows.push({
      id: 'agent-default-model',
      name: '@deepseek-ai/dsh-agent-default-model',
      config: { provider: spec.modelRoute.provider, model: spec.modelRoute.model },
    })

    // 3. MCP 可见性：按 serverName 白名单过滤 host 层 MCP 工具（决策 6）。
    //    空数组 = 不暴露任何 mcp__* 工具。
    rows.push({
      id: 'mcp-visibility',
      name: MCP_VISIBILITY_PLUGIN,
      config: { allowedServers: spec.mcp },
    })

    return { rows }
  }

  /** PluginGraph → agent.cordis.yml 文本（含 generated 头）。 */
  serialize(graph: PluginGraph): string {
    // lineWidth: 0 禁用折行，避免 YAML 库对 persona 块标量做多余换行；块标量由库自动选择。
    const body = stringify(graph.rows, { lineWidth: 0 })
    return GENERATED_HEADER + body
  }

  /** spec → preset.yml 文本（只含显示元数据，id 是目录名不可写）。 */
  compileMeta(spec: AgentSpec): string {
    return GENERATED_HEADER + stringify({ name: spec.name, description: spec.description }, { lineWidth: 0 })
  }
}
