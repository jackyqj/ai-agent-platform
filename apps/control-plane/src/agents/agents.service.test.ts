import assert from 'node:assert/strict'
import { test } from 'node:test'
import { PgStore } from '../store/pg.store.js'
import { DEFAULT_CATALOG } from './catalog.js'
import { AgentComposer } from './composer.js'
import { MemoryPresetFileStore } from './preset-file-store.js'
import { AgentsService, SpecValidationError } from './agents.service.js'
import type { AgentSpec } from './types.js'

// P0/P1 单测走 memory 回退：PgStore(undefined)（pool=null）+ MemoryPresetFileStore（不碰磁盘）。
function makeService() {
  return new AgentsService(
    new PgStore(undefined),
    new AgentComposer(DEFAULT_CATALOG),
    new MemoryPresetFileStore(),
  )
}

test('getSpec: 无工作副本时回退到种子 spec（version=1，dirty=false）', async () => {
  const svc = makeService()
  const view = await svc.getSpec('hr-assistant')
  assert.equal(view.spec.id, 'hr-assistant')
  assert.deepEqual(view.spec.mcp, ['kb'])
  assert.equal(view.dirty, false)
  assert.equal(view.version, 1)
  assert.ok(view.spec.persona.includes('knowledge_search'))
})

test('putSpec: 保存草稿置 dirty，不 bump version', async () => {
  const svc = makeService()
  const seed = (await svc.getSpec('assistant')).spec
  await svc.putSpec('assistant', { ...seed, persona: '新的 persona' }, 'u-dev')
  const view = await svc.getSpec('assistant')
  assert.equal(view.dirty, true)
  assert.equal(view.spec.persona, '新的 persona')
  assert.equal(view.version, 1, '保存草稿不得 bump version')
})

test('putSpec: 非法 spec（未知 mcp）抛 SpecValidationError', async () => {
  const svc = makeService()
  const seed = (await svc.getSpec('assistant')).spec
  await assert.rejects(
    svc.putSpec('assistant', { ...seed, mcp: ['nope'] }, 'u-dev'),
    SpecValidationError,
  )
})

test('putSpec: spec.id 与路径 id 不一致报错', async () => {
  const svc = makeService()
  const seed = (await svc.getSpec('assistant')).spec
  await assert.rejects(svc.putSpec('hr-assistant', seed, 'u-dev'), /不一致/)
})

test('publishSpec: compile + 写文件 + 修订 + version+1', async () => {
  const svc = makeService()
  const files = (svc as unknown as { files: MemoryPresetFileStore }).files
  const r = await svc.publishSpec('hr-assistant', 1, 'u-admin')
  assert.equal(r.version, 2)
  assert.equal(r.agent.status, 'published')
  const written = files.get('hr-assistant')
  assert.ok(written, '应写入 preset 文件')
  assert.ok(written!.cordisYaml.includes('@deepseek-ai/dsh-persona'))
  assert.ok(written!.cordisYaml.includes('allowedServers'))
  assert.ok(written!.cordisYaml.includes('kb'))
  const revs = await svc.listRevisions('hr-assistant')
  assert.equal(revs.length, 1)
  assert.equal(revs[0]!.version, 2)
})

test('publishSpec: 乐观并发（expectedVersion 过期）抛 version conflict', async () => {
  const svc = makeService()
  await svc.publishSpec('hr-assistant', 1, 'u-admin') // → v2
  await assert.rejects(svc.publishSpec('hr-assistant', 1, 'u-admin'), /version conflict/)
})

test('publishSpec: 写出的 YAML 含 generated 头与白名单，且不放 pinned', async () => {
  const svc = makeService()
  const files = (svc as unknown as { files: MemoryPresetFileStore }).files
  await svc.publishSpec('report-builder', 1, 'u-admin')
  const written = files.get('report-builder')
  assert.ok(written)
  assert.ok(written!.cordisYaml.startsWith('# GENERATED by AgentComposer'))
  assert.ok(written!.cordisYaml.includes('private/qwen-72b'))
  assert.ok(!written!.cordisYaml.includes('pinned'), 'pinned 不写进 YAML')
  assert.ok(written!.cordisYaml.includes('allowedServers: []'), 'mcp 空数组仍输出可见性行')
})

test('rollback: 回滚到指定修订 = 新版本，spec 回到该修订', async () => {
  const svc = makeService()
  await svc.publishSpec('hr-assistant', 1, 'u-admin') // v2（种子 persona）
  const seed = (await svc.getSpec('hr-assistant')).spec
  await svc.putSpec('hr-assistant', { ...seed, persona: '改过的 persona' }, 'u-dev')
  await svc.publishSpec('hr-assistant', 2, 'u-admin') // v3（改过）
  const r = await svc.rollback('hr-assistant', 2, 'u-admin')
  assert.equal(r.version, 4, '回滚产生新版本而非改写历史')
  const view = await svc.getSpec('hr-assistant')
  assert.equal(view.spec.persona, seed.persona, '回滚后 spec 回到 v2')
  const revs = await svc.listRevisions('hr-assistant')
  assert.deepEqual(revs.map((x) => x.version), [4, 3, 2])
})

test('capabilities: 返回模型 + MCP + host-plane', () => {
  const svc = makeService()
  const cat = svc.capabilities()
  assert.ok(cat.models.length >= 2)
  assert.ok(cat.mcpServers.some((m) => m.serverName === 'kb'))
  assert.ok(cat.hostPlane.length >= 1)
})

test('validateSpec: 直接校验不落库', () => {
  const svc = makeService()
  const seed: AgentSpec = {
    id: 'x', name: 'x', description: '', visibility: {}, approvalLevel: 'none',
    modelRoute: { provider: 'gateway', model: 'private/qwen-72b', pinned: false },
    persona: 'p', mcp: ['kb'],
  }
  assert.deepEqual(svc.validateSpec(seed), { ok: true })
  assert.equal(svc.validateSpec({ ...seed, mcp: ['nope'] }).ok, false)
})

test('propose/approve: 复制已发布 spec 为工作副本，approve 走 publishSpec（不再复制模板 YAML）', async () => {
  const svc = makeService()
  const files = (svc as unknown as { files: MemoryPresetFileStore }).files
  await svc.propose({ id: 'hr-flow', name: 'HR 流程助手', description: '流程咨询', basedOn: 'hr-assistant' }, 'u-dev')
  const view = await svc.getSpec('hr-flow')
  assert.equal(view.spec.id, 'hr-flow')
  assert.equal(view.spec.name, 'HR 流程助手')
  assert.deepEqual(view.spec.mcp, ['kb'], '继承模板的 mcp 白名单')
  assert.equal(view.dirty, true, 'propose 写入了工作副本')
  assert.equal(files.get('hr-flow'), undefined, 'propose 不写文件')

  await svc.approve('hr-flow', 'u-admin')
  const written = files.get('hr-flow')
  assert.ok(written, 'approve 走 publishSpec，应写 preset 文件')
  assert.ok(written!.cordisYaml.includes('allowedServers'))
  const preset = await svc.get('hr-flow')
  assert.equal(preset?.status, 'published')
  assert.equal(preset?.version, 2)
})
