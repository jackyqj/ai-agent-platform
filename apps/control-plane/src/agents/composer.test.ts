import assert from 'node:assert/strict'
import { test } from 'node:test'
import { DEFAULT_CATALOG } from './catalog.js'
import { AgentComposer } from './composer.js'
import type { AgentSpec } from './types.js'

const composer = new AgentComposer(DEFAULT_CATALOG)

// docs/agent-orchestration-design.md §4.2 的 4 份种子意图（persona 为占位，P1 迁移时对齐现网文案）。
const SEEDS: AgentSpec[] = [
  {
    id: 'assistant', name: '通用助手', description: '日常问答、文档起草、信息整理',
    visibility: {}, approvalLevel: 'none',
    modelRoute: { provider: 'deepseek-official', model: 'deepseek-ai/deepseek-v4-flash-0731', pinned: false },
    persona: '你是公司通用助手。\n回答直接、平实、可执行。',
    mcp: [],
  },
  {
    id: 'hr-assistant', name: 'HR 制度助手', description: '报销/请假/差旅制度问答',
    visibility: {}, approvalLevel: 'none',
    modelRoute: { provider: 'deepseek-official', model: 'deepseek-ai/deepseek-v4-flash-0731', pinned: false },
    persona: '你是 HR 制度助手。\n必须先用 knowledge_search 检索，以检索结果为唯一事实来源。',
    mcp: ['kb'],
  },
  {
    id: 'doc-search', name: '研发文档检索', description: '检索研发规范/设计/FAQ',
    visibility: {}, approvalLevel: 'none',
    modelRoute: { provider: 'deepseek-official', model: 'deepseek-ai/deepseek-v4-flash-0731', pinned: false },
    persona: '你是研发文档检索助手。\n标注出处文档。',
    mcp: ['kb'],
  },
  {
    id: 'report-builder', name: '数据报表助手', description: '数据库只读查询与汇总',
    visibility: { roles: ['developer', 'admin'] }, approvalLevel: 'self',
    modelRoute: { provider: 'gateway', model: 'private/qwen-72b', pinned: true },
    persona: '你是数据报表助手。\n先看表结构再 SELECT，工具返回什么就汇报什么。',
    mcp: [],
  },
]

test('validate: 4 份种子全部 ok', () => {
  for (const spec of SEEDS) {
    assert.deepEqual(composer.validate(spec), { ok: true }, `${spec.id} 应合法`)
  }
})

test('validate: 未知 modelRoute / 未知 mcp / 坏 id / 空 persona 均报错并指向路径', () => {
  const bad = { ...SEEDS[0]!, modelRoute: { provider: 'nope', model: 'x', pinned: false } }
  const r1 = composer.validate(bad)
  assert.equal(r1.ok, false)
  if (!r1.ok) assert.equal(r1.errors[0]?.path, 'modelRoute')

  const badMcp = { ...SEEDS[0]!, mcp: ['nope'] }
  const r2 = composer.validate(badMcp)
  assert.equal(r2.ok, false)
  if (!r2.ok) assert.equal(r2.errors[0]?.path, 'mcp')

  const badId = { ...SEEDS[0]!, id: 'Bad_Id' }
  const r3 = composer.validate(badId)
  assert.equal(r3.ok, false)
  if (!r3.ok) assert.equal(r3.errors[0]?.path, 'id')

  const badPersona = { ...SEEDS[0]!, persona: '  ' }
  const r4 = composer.validate(badPersona)
  assert.equal(r4.ok, false)
  if (!r4.ok) assert.equal(r4.errors[0]?.path, 'persona')
})

test('compile: IR 行顺序固定为 persona → model → mcp-visibility', () => {
  const graph = composer.compile(SEEDS[1]!) // hr-assistant
  assert.deepEqual(graph.rows.map(r => r.id), ['persona', 'agent-default-model', 'mcp-visibility'])
  assert.deepEqual(graph.rows.map(r => r.name), [
    '@deepseek-ai/dsh-persona',
    '@deepseek-ai/dsh-agent-default-model',
    '@deepseek-ai/dsh-tool-mcp-visibility',
  ])
})

test('compile: persona 行 config.text = spec.persona；模型行不写 pinned', () => {
  const graph = composer.compile(SEEDS[3]!) // report-builder，pinned: true
  const persona = graph.rows[0]!
  const model = graph.rows[1]!
  assert.equal((persona.config as Record<string, unknown>).text, SEEDS[3]!.persona)
  assert.deepEqual(model.config, { provider: 'gateway', model: 'private/qwen-72b' })
  assert.ok(!('pinned' in (model.config as Record<string, unknown>)))
})

test('compile: mcp 白名单进 mcp-visibility 行；空数组仍输出该行（deny 全部）', () => {
  const withKb = composer.compile(SEEDS[1]!)
  assert.deepEqual((withKb.rows[2]!.config as Record<string, unknown>).allowedServers, ['kb'])
  const noMcp = composer.compile(SEEDS[0]!)
  assert.deepEqual((noMcp.rows[2]!.config as Record<string, unknown>).allowedServers, [])
})

test('serialize: 含 generated 头、persona 块标量、幂等（逐字节一致）', () => {
  const graph = composer.compile(SEEDS[1]!)
  const yaml = composer.serialize(graph)
  assert.ok(yaml.startsWith('# GENERATED by AgentComposer — do not edit by hand.\n'))
  // persona 多行文本应由 YAML 库序列化为块标量（|- 或 |）
  assert.match(yaml, /text:\s*[|>][-]?/)
  assert.ok(yaml.includes('allowedServers:'))
  assert.ok(yaml.includes("['kb']") || yaml.includes('- kb'))
  assert.equal(composer.serialize(graph), yaml, '同一 graph 序列化应逐字节一致')
})

test('serialize: 用户字符串只进字面量位置，不出现 !!js', () => {
  for (const spec of SEEDS) {
    const yaml = composer.serialize(composer.compile(spec))
    assert.ok(!yaml.includes('!!js'), `${spec.id} 产物不得含 !!js`)
  }
})

test('compile: 绑定 skill 时在 mcp 之后追加 skill-filesystem + tool-skill', () => {
  const spec: AgentSpec = { ...SEEDS[0]!, skills: [{ skillId: 'sk-1', version: '1.2.0' }] }
  const graph = composer.compile(spec)
  assert.deepEqual(graph.rows.map(r => r.id), [
    'persona', 'agent-default-model', 'mcp-visibility', 'skill-filesystem', 'tool-skill',
  ])
  const fs = graph.rows[3]!
  assert.equal(fs.name, '@deepseek-ai/dsh-skill-filesystem')
  assert.equal((fs.config as Record<string, unknown>).includeDefaultRoots, false)
})

test('validate: latest 或非法 semver 被拒绝', () => {
  const latest = composer.validate({ ...SEEDS[0]!, skills: [{ skillId: 'sk', version: 'latest' }] })
  assert.equal(latest.ok, false)
  const bad = composer.validate({ ...SEEDS[0]!, skills: [{ skillId: 'sk', version: '1' }] })
  assert.equal(bad.ok, false)
})

test('serialize: skill 绑定产物含 compiler-owned !!js customSkillDirs', () => {
  const spec: AgentSpec = { ...SEEDS[0]!, skills: [{ skillId: 'sk-1', version: '0.1.0' }] }
  const yaml = composer.serialize(composer.compile(spec))
  assert.match(yaml, /!!js/)
  assert.match(yaml, /skills\//)
  assert.match(yaml, /@deepseek-ai\/dsh-tool-skill/)
  assert.ok(!yaml.includes('PRESET_RELATIVE_SKILLS'))
})

test('compileMeta: preset.yml 只含 name/description，带 generated 头', () => {
  const meta = composer.compileMeta(SEEDS[0]!)
  assert.ok(meta.startsWith('# GENERATED by AgentComposer — do not edit by hand.\n'))
  assert.ok(meta.includes('name: 通用助手'))
  assert.ok(meta.includes('description: 日常问答、文档起草、信息整理'))
})
