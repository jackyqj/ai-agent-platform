test('publishSpec: compile + 写文件 + 修订 + version+1', async () => {
  const svc = makeService()
  const files = (svc as unknown as { files: MemoryPresetFileStore }).files
  const r = await svc.publishSpec('hr-assistant', 0, 'u-admin') // 种子 v0 → 首次发布 v1
  assert.equal(r.version, 1)
  assert.equal(r.agent.status, 'published')
  const written = files.get('hr-assistant')
  assert.ok(written, '应写入 preset 文件')
  assert.ok(written!.cordisYaml.includes('@deepseek-ai/dsh-persona'))
  assert.ok(written!.cordisYaml.includes('allowedServers'))
  assert.ok(written!.cordisYaml.includes('kb'))
  const revs = await svc.listRevisions('hr-assistant')
  assert.equal(revs.length, 1)
  assert.equal(revs[0]!.version, 1)
})

